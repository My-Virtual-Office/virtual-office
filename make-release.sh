#!/usr/bin/env bash
# Package the whole project into a zip that runs on a clean machine with:
#
#     unzip virtual-office.zip && cd virtual-office && docker compose up -d --build
#
# What makes that one command enough:
#   - a real .env is generated and included (compose cannot start without one)
#   - COMPOSE_PROFILES=seed in that .env, so the Northstar demo data seeds itself
#     on first boot instead of needing `--profile seed`
#
# What is deliberately left out: node_modules (1.3G) and backend/*/target (292M).
# Both are produced inside the Docker build; shipping them would only bloat the
# zip and risk a stale jar overwriting a fresh compile.
set -euo pipefail
cd "$(dirname "$0")"

OUT="${1:-/run/media/sersawy/Main Disk/project/virtual-office.zip}"
STAGE="$(mktemp -d)"
APP="$STAGE/virtual-office"
trap 'rm -rf "$STAGE"' EXIT

echo "staging..."
mkdir -p "$APP"

# rsync rather than `git archive`: the tree contains four nested git repos plus
# untracked-but-needed files (.env, shots/*.png), and we want the working tree.
rsync -a --quiet \
  --exclude='.git/' --exclude='.git' \
  --exclude='node_modules/' \
  --exclude='target/' \
  --exclude='build/' \
  --exclude='.gradle/' \
  --exclude='.dart_tool/' \
  --exclude='__pycache__/' \
  --exclude='.venv/' \
  --exclude='*.log' \
  --exclude='.DS_Store' \
  --exclude='.idea/' --exclude='.vscode/' \
  --exclude='SkyOffice/client/dist/' \
  --exclude='website/build/' \
  --exclude='.env' \
  ./ "$APP/"

# ── .env ─────────────────────────────────────────────────────────────────────
# Fresh infrastructure credentials: the target machine starts with empty volumes,
# so these are set on first boot and never have to match this machine's.
# Agora + the model provider are copied from the local .env because voice and the
# assistant genuinely cannot work without them.
gen() { head -c 32 /dev/urandom | base64 | tr -d '/+=' | head -c 40; }
val() { grep -E "^$1=" .env 2>/dev/null | head -1 | cut -d= -f2- || true; }

cat > "$APP/.env" <<EOF
# Generated by make-release.sh — everything needed for \`docker compose up\`.
#
# CONTAINS REAL CREDENTIALS (Agora + model provider). Do not publish this zip.
#
# Seed the demo on first boot. This is why plain \`docker compose up\` is enough:
# compose reads COMPOSE_PROFILES from here, so the seeder is included.
COMPOSE_PROFILES=seed

# --- infrastructure: generated fresh for this machine ------------------------
JWT_SECRET=$(gen)$(gen)
INTERNAL_API_TOKEN=$(gen)
MYSQL_ROOT_PASSWORD=$(gen)
MYSQL_DATABASE=virtual_office
POSTGRES_DB=workspace
POSTGRES_USER=workspace
POSTGRES_PASSWORD=$(gen)
MONGO_ROOT_USERNAME=root
MONGO_ROOT_PASSWORD=$(gen)
RABBITMQ_USER=guest
RABBITMQ_PASSWORD=$(gen)
GRAFANA_USER=admin
GRAFANA_PASSWORD=admin

# --- host-facing URLs --------------------------------------------------------
# Baked into the browser bundles at BUILD time. localhost is right when you open
# the demo on the machine running it. To reach it from another device on the LAN,
# put this machine's IP here and rebuild (docker compose up -d --build).
# Note: browsers block the microphone on a plain-http LAN origin, so voice needs
# localhost or https.
PUBLIC_GATEWAY_URL=http://localhost:8080
PUBLIC_COLYSEUS_WS=ws://localhost:2567
PUBLIC_ROOM_WS=ws://localhost:8086

# --- voice/video (Agora) -----------------------------------------------------
AGORA_APP_ID=$(val AGORA_APP_ID)
AGORA_APP_CERTIFICATE=$(val AGORA_APP_CERTIFICATE)

# --- the assistant -----------------------------------------------------------
# Leave OPENAI_API_KEY blank to run without the assistant: ai-service starts and
# returns 503 on /api/ai/chat; nothing else is affected.
OPENAI_API_KEY=$(val OPENAI_API_KEY)
OPENAI_MODEL=$(val OPENAI_MODEL)
OPENAI_BASE_URL=$(val OPENAI_BASE_URL)

# --- demo seed ---------------------------------------------------------------
SEED_PASSWORD=Northstar@2026
EOF

echo "zipping..."
rm -f "$OUT"
( cd "$STAGE" && zip -qr "$OUT" virtual-office )
echo "$(du -h "$OUT" | cut -f1)  $OUT"
